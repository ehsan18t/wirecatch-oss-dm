// The named steps of the size scales in app.css. Components take one of these names, never a
// pixel value, so every size in the app is set in one place.

/** An icon size; each is a `--icon-*` token. */
export type IconSize = 'xs' | 'sm' | 'md' | 'lg';

/** A dialog width: the design system's medium or large dialog. */
export type DialogSize = 'medium' | 'wide';
