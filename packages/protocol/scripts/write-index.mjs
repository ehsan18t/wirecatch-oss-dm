// Writes src/index.ts re-exporting every generated type and the generated constants, so
// consumers import from "@wirecatch/protocol" without knowing the file layout.
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const generated = join(root, "src", "generated");
// Written by the generator test in crates/protocol/src/exported.rs: values, not a type.
const CONSTANTS = "constants";
const files = readdirSync(generated)
  .filter((f) => f.endsWith(".ts"))
  .map((f) => f.slice(0, -3));
if (!files.includes(CONSTANTS)) {
  throw new Error(`src/generated/${CONSTANTS}.ts is missing; it is written by \`cargo test -p wirecatch-protocol\`.`);
}
const names = files.filter((n) => n !== CONSTANTS).sort();

const lines = [
  "// Generated by scripts/write-index.mjs. Run `pnpm protocol:generate` after changing crates/protocol.",
  `export * from "./generated/${CONSTANTS}";`,
  ...names.map((n) => `export type { ${n} } from "./generated/${n}";`),
  "",
];
writeFileSync(join(root, "src", "index.ts"), lines.join("\n"));
console.log(`index.ts exports the constants and ${names.length} types`);
