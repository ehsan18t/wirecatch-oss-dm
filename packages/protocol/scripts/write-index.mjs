// Writes src/index.ts re-exporting every generated type, so consumers import
// from "@wirecatch/protocol" without knowing the file layout.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const generated = join(root, "src", "generated");
const names = readdirSync(generated)
  .filter((f) => f.endsWith(".ts"))
  .map((f) => f.slice(0, -3))
  .sort();

// Constants are not types, so ts-rs does not export them; read them from the crate.
const librs = readFileSync(join(root, "..", "..", "crates", "protocol", "src", "lib.rs"), "utf8");
const version = librs.match(/pub const PROTOCOL_VERSION: u32 = (\d+);/);
if (!version) throw new Error("PROTOCOL_VERSION not found in crates/protocol/src/lib.rs");

const lines = [
  "// Generated by scripts/write-index.mjs. Run `pnpm protocol:generate` after changing crates/protocol.",
  `/** Bumped on any incompatible change to the wire format. */`,
  `export const PROTOCOL_VERSION = ${version[1]};`,
  ...names.map((n) => `export type { ${n} } from "./generated/${n}";`),
  "",
];
writeFileSync(join(root, "src", "index.ts"), lines.join("\n"));
console.log(`index.ts exports ${names.length} types`);
