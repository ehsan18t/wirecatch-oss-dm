// The text of src/index.ts, which scripts/generate.mjs writes: it re-exports every generated type and the generated constants, so consumers import from "@wirecatch/protocol" without knowing the file layout.
import { readdirSync } from 'node:fs';
import { VALIDATORS } from './validators.mjs';

// Written by the generator test in crates/protocol/src/exported.rs: values, not a type.
const CONSTANTS = 'constants';
const EXTENSION = '.ts';
/** Files of values, not of one type each, exported whole. */
const VALUES = [CONSTANTS, VALIDATORS];
/** Files written by hand next to the generated folder, in src, exported whole: what TypeScript needs beyond the types and constants, such as the constructors of branded ids. */
export const HAND_WRITTEN = ['extension-settings', 'ids'];

/** The index for the generated files in `folder`; throws when the constants file is missing. */
export function indexSource(folder) {
  const files = readdirSync(folder)
    .filter((f) => f.endsWith(EXTENSION))
    .map((f) => f.slice(0, -EXTENSION.length));
  if (!files.includes(CONSTANTS)) {
    throw new Error(
      `${CONSTANTS}${EXTENSION} was not generated; run \`pnpm protocol:generate\`, whose protocol tests write it.`,
    );
  }
  const names = files.filter((n) => !VALUES.includes(n)).sort();
  const lines = [
    '// Generated by scripts/generate.mjs. Run `pnpm protocol:generate` after changing crates/protocol.',
    ...VALUES.filter((n) => files.includes(n)).map((n) => `export * from "./generated/${n}";`),
    ...HAND_WRITTEN.map((n) => `export * from "./${n}";`),
    ...names.map((n) => `export type { ${n} } from "./generated/${n}";`),
    '',
  ];
  return lines.join('\n');
}
